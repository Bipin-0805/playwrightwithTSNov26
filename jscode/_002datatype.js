//Data Types in JavaScript

let age = 25; // Number
let name = "John Doe"; // String
let isStudent = true; // Boolean
let hobbies = ["reading", "traveling", "coding"]; // Array
let address = { street: "123 Main St", city: "New York", country: "USA" }; // Object
let nullValue = null; // Null
let undefinedValue; // Undefined

console.log(typeof age); // Output: number
console.log(typeof name); // Output: string
console.log(typeof isStudent); // Output: boolean
console.log(typeof hobbies); // Output: object
console.log(typeof address); // Output: object
console.log(typeof nullValue); // Output: object (this is a known quirk in JavaScript)
console.log(typeof undefinedValue); // Output: undefined

let largeNUmber = 1234567890123456789012345678901234567890n; // BigInt
console.log(typeof largeNUmber); // Output: bigint


